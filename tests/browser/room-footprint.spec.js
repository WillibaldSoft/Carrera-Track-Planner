import { test, expect } from '@playwright/test'
for (const lang of ['de', 'en', 'fr'])
  test(`new track starts with room, edits footprint and continues (${lang})`, async ({ page }) => {
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.goto('/')
    await page.getByTestId('standalone-language').selectOption(lang)
    await page.getByTestId('standalone-new').click()
    await expect(page.getByTestId('room-footprint-editor')).toBeVisible()
    await expect(page.getByTestId('graph-track-canvas')).toBeHidden()
    await page.getByTestId('room-template-name').fill('Atelier ' + lang)
    await page.getByTestId('room-widthM').fill('7')
    await page.getByTestId('room-add-obstacle').click()
    await page.getByTestId('room-feature-name').fill('Kamin')
    await page.getByTestId('room-feature-widthM').fill('0.8')
    await page.getByTestId('room-feature-depthM').fill('0.6')
    await page.getByTestId('room-add-extension').click()
    await page.getByTestId('room-feature-name').fill('Fensternische')
    await page.getByTestId('room-feature-widthM').fill('1.2')
    await page.getByTestId('room-feature-depthM').fill('1.6')
    await page.getByTestId('room-feature-yM').fill('1')
    await page.getByTestId('room-continue').click()
    await expect(page.getByTestId('track-room-background')).toBeVisible()
    await expect(page.getByTestId('track-room-background').getByTestId('room-outline')).toHaveAttribute('d', /8200/)
    await page.getByTestId('add-track-piece').click()
    await page.locator('.planner-name').fill('Room track ' + lang)
    const origin = await page.getByTestId('room-origin-xMm').inputValue()
    await page.getByTestId('add-track-piece').click()
    await expect(page.getByTestId('room-origin-xMm')).toHaveValue(origin)
    await page.getByTestId('room-origin-xMm').fill('-2000')
    await page.getByTestId('room-origin-xMm').press('Tab')
    await page.getByTestId('room-background-visible').uncheck()
    await expect(page.getByTestId('track-room-background')).toHaveCount(0)
    await page.getByTestId('room-background-visible').check()
    const saved = page.waitForResponse((r) => r.url().endsWith('/api/tracks') && r.request().method() === 'POST')
    await page.getByTestId('planner-save').click()
    expect((await saved).ok()).toBe(true)
    await page.getByTestId('planner-nav-files').click()
    const download = page.waitForEvent('download')
    await page.getByTestId('export-track-json').click()
    await download
    await page
      .getByRole('button', { name: lang === 'de' ? 'Abbrechen' : lang === 'fr' ? 'Annuler' : 'Cancel', exact: true })
      .click()
    await page.getByTestId('standalone-new').click()
    await expect(page.getByTestId('room-template-select')).toContainText('Atelier ' + lang)
    const options = page.getByTestId('room-template-select').locator('option')
    const value = await options.nth(1).getAttribute('value')
    await page.getByTestId('room-template-select').selectOption(value)
    await expect(page.locator('[data-room-feature]')).toHaveCount(2)
    await page.getByTestId('room-continue').click()
    await expect(page.getByTestId('track-room-background')).toBeVisible()
    expect(errors).toEqual([])
  })
test('room features can be dragged, nudged by keyboard and removed', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(crypto, 'randomUUID', { value: undefined }))
  await page.goto('/')
  await page.getByTestId('standalone-new').click()
  await page.getByTestId('room-add-obstacle').click()
  const feature = page.locator('[data-room-feature="obstacle"]')
  const b = await feature.boundingBox()
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width / 2 + 40, b.y + b.height / 2 + 25, { steps: 5 })
  await page.mouse.up()
  const x = Number(await page.getByTestId('room-feature-xM').inputValue())
  expect(x).toBeGreaterThan(0)
  await feature.focus()
  await feature.press('ArrowRight')
  expect(Number(await page.getByTestId('room-feature-xM').inputValue())).toBeCloseTo(x + 0.01, 2)
  await page.getByTestId('room-remove-feature').click()
  await expect(feature).toHaveCount(0)
})
test('invalid disconnected alcove blocks continuation and can be corrected', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('standalone-new').click()
  await page.getByTestId('room-add-extension').click()
  await page.getByTestId('room-feature-xM').fill('9')
  await expect(page.getByTestId('room-shape-invalid')).toBeVisible()
  await expect(page.getByTestId('room-continue')).toBeDisabled()
  await page.getByTestId('room-feature-xM').fill('-1')
  await expect(page.getByTestId('room-continue')).toBeEnabled()
  await page.getByTestId('room-continue').click()
  await expect(page.getByTestId('track-room-background')).toBeVisible()
})
